-- Слайд 9: Приведение типов

print("=== Явное преобразование ===")
print(tonumber("42") + 1) --> 43
print(tostring(42) .. "!") --> 42!

print("=== Неявное приведение в арифметике ===")
print("10" + 5)  --> 15
print("a" .. 1)  --> a1

print("=== Truthy / falsy значения ===")
-- Единственные «ложные» значения в условиях — nil и false
-- 0 и "" — истина (в отличие от многих других языков)
if 0 then print("0 истинно") end
--> 0 истинно (0 не является ложным)

if "" then print("пустая строка истинна") end
--> пустая строка истинна

if not nil then print("nil ложно") end
if not false then print("false ложно") end
