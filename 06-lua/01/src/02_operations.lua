-- Слайд 8: Операции над типами

print("=== Арифметические операции ===")
print(7 + 3)   --> 10
print(7 - 3)   --> 4
print(7 * 3)   --> 21
print(7 / 3)   --> 2.3333333333333
print(7 // 3)  --> 2  (целочисленное деление)
print(7 % 3)   --> 1  (остаток)
print(2 ^ 10)  --> 1024.0 (возведение в степень)

print("=== Конкатенация строк ===")
print("Hello" .. ", " .. "world!")

print("=== Операции сравнения ===")
print(3 == 3)   --> true
print(3 ~= 4)   --> true
print(3 < 4)    --> true
print(4 > 3)    --> true
print(3 <= 3)   --> true
print(4 >= 5)   --> false

print("=== Логические операции ===")
-- and / or / not работают с любыми типами, не только boolean
print(1 and 2)        --> 2   (and возвращает второй операнд, если первый истинен)
print(nil and 2)      --> nil (and возвращает первый операнд, если он ложен)
print(false or "x")   --> x   (or возвращает второй операнд, если первый ложен)
print("a" or "b")     --> a   (or возвращает первый операнд, если он истинен)
print(not nil)        --> true
print(not 0)          --> false (0 истинно в Lua!)
