-- Слайд 10: Области видимости
-- По умолчанию переменные глобальные — нужно явно писать local
-- Лексическая (статическая) область видимости
-- Блоки задаются конструкцией do ... end

print("=== Локальные переменные и блоки do...end ===")

local x = 10
do
  local x = 20  -- новая переменная, видна только внутри блока
  print("внутри блока x =", x) --> 20
end
print("вне блока x =", x) --> 10

print("=== Глобальная vs локальная переменная ===")
y = 100        -- глобальная переменная (без local)
local y = 200  -- локальная переменная, "затеняет" глобальную в этой области
print("локальная y =", y)        --> 200
print("глобальная _G.y =", _G.y) --> 100
