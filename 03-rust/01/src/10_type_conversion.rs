// Слайд 10: "Явное преобразование типов"
//
// Rust не выполняет числовые преобразования неявно.

fn main() {
    let x: i32 = 10;

    // Ошибка компиляции, если раскомментировать (mismatched types):
    // let y: f64 = x + 1.0;

    // Правильно — явное преобразование через `as`:
    let y: f64 = x as f64;
    println!("y = {y}");
}
